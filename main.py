# ============================================================
# 3D SNAKE GAME — ИГРА "ЗМЕЙКА" С ТРЁХМЕРНЫМИ ЭФФЕКТАМИ
# Библиотека: turtle (встроенная, установка не требуется)
# ============================================================
import turtle  # Графика и анимация (встроенная библиотека Python)
import random  # Генерация случайных чисел для позиции еды
import time  # Работа с временем для задержек и анимации

# ============================================================
# ГЛОБАЛЬНЫЕ ПЕРЕМЕННЫЕ
# ============================================================
score = 0  # Текущий счёт игрока
high_score = 0  # Рекорд за текущую сессию
segments = []  # Список сегментов тела змеи

# ============================================================
# НАСТРОЙКА ОКНА ИГРЫ
# ============================================================
screen = turtle.Screen()  # Создание игрового окна
screen.title("3D Snake Game — Змейка")  # Заголовок окна
screen.bgcolor("#1a1a2e")  # Тёмно-синий фон (цвет космоса)
screen.setup(600, 650)  # Размер окна: 600×650 пикселей
screen.tracer(0)  # Отключение автоматического обновления (для плавности)

# ============================================================
# ОТРИСОВКА ИГРОВОЙ РАМКИ
# ============================================================
border = turtle.Turtle()  # Создание черепашки для рамки
border.penup()  # Поднять перо (без рисования при перемещении)
border.goto(-250, -250)  # Перейти в левый нижний угол
border.pendown()  # Опустить перо (начать рисование)
border.pensize(4)  # Установить толщину линии 4 пикселя
border.pencolor("#e94560")  # Установить красный цвет линии
for _ in range(4):  # Цикл для рисования 4 сторон квадрата
    border.forward(500)  # Нарисовать линию длиной 500 пикселей
    border.left(90)  # Повернуть на 90 градусов влево
border.hideturtle()  # Скрыть черепашку после рисования

# ============================================================
# СОЗДАНИЕ ГОЛОВЫ ЗМЕИ
# ============================================================
head = turtle.Turtle()  # Создание черепашки для головы
head.shape("square")  # Установка квадратной формы
head.shapesize(1.2, 1.2)  # Увеличение размера (1.2× от стандартного)
head.color("#00ff88")  # Установка ярко-зелёного цвета
head.penup()  # Поднять перо (не оставлять след)
head.goto(0, 0)  # Начальная позиция — центр экрана
head.direction = "stop"  # Начальное состояние — без движения

# ============================================================
# 3D-БЛИК НА ГОЛОВЕ (световой блик для эффекта объёма)
# ============================================================
shine = turtle.Turtle()  # Создание черепашки для блика
shine.shape("circle")  # Круглая форма
shine.shapesize(0.3)  # Маленький размер (0.3× от стандартного)
shine.color("white")  # Белый цвет
shine.penup()  # Без рисования

# ============================================================
# СОЗДАНИЕ ЕДЫ
# ============================================================
food = turtle.Turtle()  # Создание черепашки для еды
food.shape("circle")  # Круглая форма
food.shapesize(0.8)  # Размер (0.8× от стандартного)
food.color("#ff6b6b")  # Красный цвет
food.penup()  # Без рисования
food.goto(100, 100)  # Начальная позиция еды

# ============================================================
# 3D-ТЕНЬ ЕДЫ (тень для эффекта объёма)
# ============================================================
food_shadow = turtle.Turtle()  # Создание черепашки для тени
food_shadow.shape("circle")  # Круглая форма
food_shadow.shapesize(1)  # Размер чуть больше еды
food_shadow.color("#331111")  # Тёмно-красный цвет (тень)
food_shadow.penup()  # Без рисования
food_shadow.goto(97, 97)  # Начальная позиция со смещением на 3 пикселя

# ============================================================
# ОТОБРАЖЕНИЕ СЧЁТА
# ============================================================
score_display = turtle.Turtle()  # Создание черепашки для текста счёта
score_display.penup()  # Без рисования
score_display.color("white")  # Белый цвет текста
score_display.goto(0, 275)  # Позиция в верхней части экрана
score_display.hideturtle()  # Скрыть черепашку


def update_score():  # Функция обновления счёта на экране
    """Очищает и заново выводит текущий счёт и рекорд"""
    score_display.clear()  # Очистить старый текст
    score_display.write(f"Счёт: {score}  |  Рекорд: {high_score}",
                        align="center", font=("Arial", 18, "bold"))


update_score()  # Первоначальный вывод счёта


# ============================================================
# ДОБАВЛЕНИЕ СЕГМЕНТА ТЕЛА ЗМЕИ
# ============================================================
def add_segment():  # Функция создания нового сегмента тела
    """Создаёт новый сегмент и добавляет его в список segments"""
    seg = turtle.Turtle()  # Новая черепашка для сегмента
    seg.shape("square")  # Квадратная форма
    seg.shapesize(0.9)  # Размер (0.9× от стандартного)
    seg.color("#00cc66")  # Зелёный цвет (темнее головы)
    seg.penup()  # Без рисования
    segments.append(seg)  # Добавить сегмент в конец списка


# ============================================================
# ФУНКЦИИ УПРАВЛЕНИЯ НАПРАВЛЕНИЕМ
# ============================================================
def go_up():  # Движение ВВЕРХ
    """Устанавливает направление 'up', если змея не движется вниз"""
    if head.direction != "down":  # Запрет разворота на 180 градусов
        head.direction = "up"


def go_down():  # Движение ВНИЗ
    """Устанавливает направление 'down', если змея не движется вверх"""
    if head.direction != "up":  # Запрет разворота
        head.direction = "down"


def go_left():  # Движение ВЛЕВО
    """Устанавливает направление 'left', если змея не движется вправо"""
    if head.direction != "right":  # Запрет разворота
        head.direction = "left"


def go_right():  # Движение ВПРАВО
    """Устанавливает направление 'right', если змея не движется влево"""
    if head.direction != "left":  # Запрет разворота
        head.direction = "right"


# ============================================================
# ПРИВЯЗКА КЛАВИШ УПРАВЛЕНИЯ
# ============================================================
screen.listen()  # Включить прослушивание нажатий клавиш
screen.onkey(go_up, "Up")  # Стрелка ВВЕРХ → движение вверх
screen.onkey(go_down, "Down")  # Стрелка ВНИЗ → движение вниз
screen.onkey(go_left, "Left")  # Стрелка ВЛЕВО → движение влево
screen.onkey(go_right, "Right")  # Стрелка ВПРАВО → движение вправо
screen.onkey(go_up, "w")  # Клавиша W → движение вверх
screen.onkey(go_down, "s")  # Клавиша S → движение вниз
screen.onkey(go_left, "a")  # Клавиша A → движение влево
screen.onkey(go_right, "d")  # Клавиша D → движение вправо


# ============================================================
# ДВИЖЕНИЕ ЗМЕИ
# ============================================================
def move():  # Главная функция перемещения змеи
    """Перемещает сегменты тела и голову в текущем направлении"""
    # Движение сегментов тела (с конца к началу)
    for i in range(len(segments) - 1, 0, -1):  # Цикл от последнего к первому
        x = segments[i - 1].xcor()  # X-координата предыдущего сегмента
        y = segments[i - 1].ycor()  # Y-координата предыдущего сегмента
        segments[i].goto(x, y)  # Переместить текущий сегмент на место предыдущего

    # Первый сегмент следует за головой
    if segments:  # Если есть хотя бы один сегмент
        x = head.xcor()  # X-координата головы
        y = head.ycor()  # Y-координата головы
        segments[0].goto(x, y)  # Переместить первый сегмент на место головы

    # Движение головы в зависимости от направления
    if head.direction == "up":  # Если направление ВВЕРХ
        head.sety(head.ycor() + 20)  # Увеличить Y на 20 пикселей
    elif head.direction == "down":  # Если направление ВНИЗ
        head.sety(head.ycor() - 20)  # Уменьшить Y на 20 пикселей
    elif head.direction == "left":  # Если направление ВЛЕВО
        head.setx(head.xcor() - 20)  # Уменьшить X на 20 пикселей
    elif head.direction == "right":  # Если направление ВПРАВО
        head.setx(head.xcor() + 20)  # Увеличить X на 20 пикселей

    # Перемещение 3D-блика за головой
    if head.direction != "stop":  # Если змея движется
        shine.goto(head.xcor() + 4, head.ycor() + 4)  # Блик со смещением 4 пикселя


# ============================================================
# ПРОВЕРКА СТОЛКНОВЕНИЙ
# ============================================================
def check_collision():  # Проверка всех типов столкновений
    """
    Проверяет:
    1) Выход за границу поля
    2) Столкновение головы с телом
    3) Поедание еды
    Возвращает True при столкновении (конец игры), иначе False
    """
    global score, high_score  # Доступ к глобальным переменным

    # ПРОВЕРКА СТОЛКНОВЕНИЯ С ГРАНИЦЕЙ ПОЛЯ
    if abs(head.xcor()) > 240 or abs(head.ycor()) > 240:  # Выход за пределы 500×500
        return True  # Игра окончена

    # ПРОВЕРКА СТОЛКНОВЕНИЯ С СОБСТВЕННЫМ ТЕЛОМ
    for seg in segments:  # Проверка каждого сегмента
        if head.distance(seg) < 15:  # Если расстояние меньше 15 пикселей
            return True  # Игра окончена

    # ПРОВЕРКА ПОЕДАНИЯ ЕДЫ
    if head.distance(food) < 20:  # Если голова рядом с едой
        # Перемещение еды в случайное место
        x = random.randint(-12, 12) * 20  # Случайная X-координата (кратно 20)
        y = random.randint(-12, 12) * 20  # Случайная Y-координата (кратно 20)
        food.goto(x, y)  # Переместить еду
        food_shadow.goto(x - 3, y - 3)  # Переместить тень со смещением

        add_segment()  # Добавить новый сегмент к змее
        score += 10  # Увеличить счёт на 10 очков
        if score > high_score:  # Если побит рекорд
            high_score = score  # Обновить рекорд
        update_score()  # Обновить отображение счёта

    return False  # Столкновений нет — игра продолжается


# ============================================================
# ЭКРАН ЗАВЕРШЕНИЯ ИГРЫ (GAME OVER)
# ============================================================
def game_over():  # Функция окончания игры
    """Отображает экран Game Over и сбрасывает игру"""
    global score  # Доступ к глобальной переменной

    # Удаление всех сегментов тела
    for seg in segments:
        seg.goto(1000, 1000)  # Переместить за пределы экрана
    segments.clear()  # Очистить список сегментов

    # Возврат головы в центр
    head.goto(0, 0)  # Центр экрана
    head.direction = "stop"  # Остановить движение

    # Отображение текста GAME OVER
    over = turtle.Turtle()  # Новая черепашка для текста
    over.penup()  # Без рисования
    over.color("#e94560")  # Красный цвет
    over.goto(0, 40)  # Позиция первой строки
    over.write("ИГРА ОКОНЧЕНА", align="center",
               font=("Arial", 28, "bold"))  # Крупный текст
    over.goto(0, -20)  # Позиция второй строки
    over.write("ПРОБЕЛ — заново", align="center",
               font=("Arial", 14, "normal"))  # Подсказка
    over.hideturtle()  # Скрыть черепашку

    score = 0  # Сбросить текущий счёт
    update_score()  # Обновить отображение


# ============================================================
# ПЕРЕЗАПУСК ИГРЫ
# ============================================================
def restart():  # Функция полного перезапуска игры
    """Очищает экран и пересоздаёт все игровые объекты заново"""
    global score, high_score, head, shine, food, food_shadow, score_display

    # Удаление старых сегментов
    for seg in segments:
        seg.goto(1000, 1000)  # Переместить за экран
    segments.clear()  # Очистить список

    screen.clearscreen()  # Полная очистка экрана

    # Перенастройка окна
    screen.bgcolor("#1a1a2e")  # Фон
    screen.setup(600, 650)  # Размер
    screen.tracer(0)  # Отключение автообновления

    # Перерисовка рамки
    new_border = turtle.Turtle()
    new_border.penup()
    new_border.goto(-250, -250)
    new_border.pendown()
    new_border.pensize(4)
    new_border.pencolor("#e94560")
    for _ in range(4):
        new_border.forward(500)
        new_border.left(90)
    new_border.hideturtle()

    # Создание новой головы
    head = turtle.Turtle()
    head.shape("square")
    head.shapesize(1.2, 1.2)
    head.color("#00ff88")
    head.penup()
    head.goto(0, 0)
    head.direction = "stop"

    # Создание нового 3D-блика
    shine = turtle.Turtle()
    shine.shape("circle")
    shine.shapesize(0.3)
    shine.color("white")
    shine.penup()

    # Создание новой еды
    food = turtle.Turtle()
    food.shape("circle")
    food.shapesize(0.8)
    food.color("#ff6b6b")
    food.penup()
    food.goto(100, 100)

    # Создание новой тени еды
    food_shadow = turtle.Turtle()
    food_shadow.shape("circle")
    food_shadow.shapesize(1)
    food_shadow.color("#331111")
    food_shadow.penup()
    food_shadow.goto(97, 97)

    # Обновление отображения счёта
    score_display = turtle.Turtle()
    score_display.penup()
    score_display.color("white")
    score_display.goto(0, 275)
    score_display.hideturtle()

    score = 0  # Сброс счёта
    update_score()  # Обновление отображения

    # Привязка клавиш управления
    screen.listen()
    screen.onkey(go_up, "Up")
    screen.onkey(go_down, "Down")
    screen.onkey(go_left, "Left")
    screen.onkey(go_right, "Right")
    screen.onkey(go_up, "w")
    screen.onkey(go_down, "s")
    screen.onkey(go_left, "a")
    screen.onkey(go_right, "d")
    screen.onkey(restart, "space")  # ПРОБЕЛ для перезапуска

    # Запуск игрового цикла
    game_loop()


# Привязка клавиши ПРОБЕЛ к перезапуску
screen.onkey(restart, "space")


# ============================================================
# ГЛАВНЫЙ ИГРОВОЙ ЦИКЛ
# ============================================================
def game_loop():  # Основной цикл игры
    """Бесконечный цикл, обновляющий игру с заданной частотой"""
    global running
    running = True
    while running:  # Цикл продолжается, пока игра активна
        screen.update()  # Обновить экран (отрисовать все изменения)
        move()  # Переместить змею

        if check_collision():  # Проверить столкновения
            game_over()  # Если есть — завершить игру
            running = False  # Остановить цикл

        # 3D-АНИМАЦИЯ ПУЛЬСАЦИИ ЕДЫ
        food.shapesize(0.8 + 0.1 * (time.time() % 0.5))  # Изменение размера

        time.sleep(0.12)  # Задержка для контроля скорости игры


# ============================================================
# ЗАПУСК ИГРЫ
# ============================================================
game_loop()  # Запуск главного игрового цикла
turtle.done()  # Корректное завершение работы библиотеки turtle